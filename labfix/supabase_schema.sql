create table if not exists public.reports (
    id bigint generated by default as identity primary key,
    student_name text not null,
    lab_name text not null,
    pc_number text not null,
    problem_type text not null,
    description text not null,
    status text not null default 'Submitted',
    created_at timestamptz not null default now()
);

-- The Flask backend uses the Supabase service-role key.
-- Keep that key only in .env and NEVER put it in HTML/JS.

alter table public.reports enable row level security;

-- The backend service role bypasses RLS, so no public INSERT policy is needed.
-- If you later want the browser itself to access Supabase directly,
-- create carefully scoped RLS policies instead of exposing the service-role key.
